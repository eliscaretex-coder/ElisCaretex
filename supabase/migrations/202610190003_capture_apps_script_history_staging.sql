do $$
declare t text;
begin
  foreach t in array array[
    'apps_script_customer_name_map','apps_script_finish_lines','apps_script_mop_lines',
    'apps_script_wash_lines','apps_script_staff_sessions','apps_script_trolley_returns']
  loop
    execute format('alter table staging.%I enable row level security', t);
    execute format('revoke all on staging.%I from anon, authenticated', t);
  end loop;
end $$;
