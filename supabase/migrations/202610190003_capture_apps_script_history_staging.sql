-- Captures the Apps Script history staging tables that were created directly in
-- the database during the 2026-09-26 historical import (batches
-- APPS_SCRIPT_*_20260926_*). They were never committed as a migration, which
-- breaks the AGENTS.md rule that every DDL change exists as a file.
--
-- The definitions below match the live objects verified read-only on
-- 2026-10-19. Every statement is idempotent: on the existing database this
-- migration changes nothing; on a fresh database it recreates the empty
-- staging layer so the reconciliation report can run.
--
-- Staging stays private: RLS enabled, no policies, no anon/authenticated grants.

create schema if not exists staging;

